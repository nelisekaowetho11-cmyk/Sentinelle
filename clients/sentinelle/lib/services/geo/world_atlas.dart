/// A geographic coordinate. `dx` is longitude, `dy` is latitude — packed into
/// [Offset] so the projection can work on it without allocating.
typedef LonLat = Offset;

List<List<LonLat>>? _cache;

/// Country rings in lon/lat. Decoded once and held.
List<List<LonLat>> worldRings() => _cache ??= _decode();

List<List<LonLat>> _decode() {
  final rings = <List<LonLat>>[];
  for (final ring in _ringData.split(';')) {
    var x = 0, y = 0;
    final points = <LonLat>[];
    for (final token in ring.split(' ')) {
      final dot = token.indexOf('.');
      x += _int(token.substring(0, dot));
      y += _int(token.substring(dot + 1));
      points.add(Offset(x / 100, y / 100));
    }
    rings.add(points);
  }
  return rings;
}

int _int(String s) => s.startsWith('-')
    ? -int.parse(s.substring(1), radix: 16)
    : int.parse(s, radix: 16);
